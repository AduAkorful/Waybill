import type { BrowserEnvironment } from './network'

/**
 * The only place the browser bundle reads process.env. Next.js inlines NEXT_PUBLIC_ variables only when they
 * are written as literal `process.env.NEXT_PUBLIC_NAME` reads, so a loop over names or a spread would silently
 * read nothing in the browser. Add every variable the app uses here.
 */
export function publicEnvironment(): BrowserEnvironment {
  return {
    NEXT_PUBLIC_WAYBILL_NETWORK: process.env.NEXT_PUBLIC_WAYBILL_NETWORK,
    NEXT_PUBLIC_WAYBILL_API_BASE_URL: process.env.NEXT_PUBLIC_WAYBILL_API_BASE_URL,
    NEXT_PUBLIC_PRIVY_APP_ID: process.env.NEXT_PUBLIC_PRIVY_APP_ID,
    NEXT_PUBLIC_PRIVY_CLIENT_ID: process.env.NEXT_PUBLIC_PRIVY_CLIENT_ID,
    NEXT_PUBLIC_WAYBILL_MAINNET_CHAIN_ID: process.env.NEXT_PUBLIC_WAYBILL_MAINNET_CHAIN_ID,
    NEXT_PUBLIC_WAYBILL_MAINNET_RPC_URL: process.env.NEXT_PUBLIC_WAYBILL_MAINNET_RPC_URL,
    NEXT_PUBLIC_WAYBILL_MAINNET_EXPLORER_URL: process.env.NEXT_PUBLIC_WAYBILL_MAINNET_EXPLORER_URL,
    NEXT_PUBLIC_WAYBILL_MAINNET_USDC_ADDRESS: process.env.NEXT_PUBLIC_WAYBILL_MAINNET_USDC_ADDRESS,
    NEXT_PUBLIC_WAYBILL_MAINNET_ESCROW_ADDRESS: process.env.NEXT_PUBLIC_WAYBILL_MAINNET_ESCROW_ADDRESS,
    NEXT_PUBLIC_WAYBILL_MAINNET_ARBITER_LIST_ADDRESS: process.env.NEXT_PUBLIC_WAYBILL_MAINNET_ARBITER_LIST_ADDRESS,
    NEXT_PUBLIC_WAYBILL_MAINNET_ATTESTOR_REGISTRY_ADDRESS: process.env.NEXT_PUBLIC_WAYBILL_MAINNET_ATTESTOR_REGISTRY_ADDRESS,
    NEXT_PUBLIC_WAYBILL_MAINNET_BOND_VAULT_ADDRESS: process.env.NEXT_PUBLIC_WAYBILL_MAINNET_BOND_VAULT_ADDRESS,
    NEXT_PUBLIC_WAYBILL_MAINNET_MULTICALL3_ADDRESS: process.env.NEXT_PUBLIC_WAYBILL_MAINNET_MULTICALL3_ADDRESS,
    NEXT_PUBLIC_WAYBILL_MAINNET_FINANCING_VAULT_ADDRESS: process.env.NEXT_PUBLIC_WAYBILL_MAINNET_FINANCING_VAULT_ADDRESS,
    NEXT_PUBLIC_WAYBILL_MAINNET_EARLY_RESOLVE: process.env.NEXT_PUBLIC_WAYBILL_MAINNET_EARLY_RESOLVE,
    NEXT_PUBLIC_WAYBILL_LOCAL_FORK: process.env.NEXT_PUBLIC_WAYBILL_LOCAL_FORK,
  }
}
